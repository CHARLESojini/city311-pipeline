-- Phase 2: least-privilege role for dbt. Reads RAW, owns BRONZE/SILVER/GOLD/REFERENCE
-- (and dev schemas like DBT_DEV_SILVER). Idempotent: safe to re-run.
-- Named CITY311_TRANSFORMER, not TRANSFORMER, so it never collides with another
-- project's dbt role on a shared account (each pipeline sees only its own data).
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS CITY311_TRANSFORMER;
GRANT ROLE CITY311_TRANSFORMER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE NYC311_WH TO ROLE CITY311_TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE NYC311 TO ROLE CITY311_TRANSFORMER;

-- Read-only on RAW: dbt never writes to landing tables
GRANT USAGE ON SCHEMA NYC311.RAW TO ROLE CITY311_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA NYC311.RAW TO ROLE CITY311_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NYC311.RAW TO ROLE CITY311_TRANSFORMER;

-- Airflow runs dbt as the existing key-pair service user
USE ROLE SECURITYADMIN;
GRANT ROLE CITY311_TRANSFORMER TO USER AIRFLOW_SVC;
