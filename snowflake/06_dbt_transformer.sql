-- Phase 2: least-privilege role for dbt. Reads RAW, owns BRONZE/SILVER/GOLD/REFERENCE
-- (and dev schemas like DBT_DEV_SILVER). Idempotent: safe to re-run.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE NYC311_WH TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE NYC311 TO ROLE TRANSFORMER;

-- Read-only on RAW: dbt never writes to landing tables
GRANT USAGE ON SCHEMA NYC311.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA NYC311.RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NYC311.RAW TO ROLE TRANSFORMER;

-- Airflow runs dbt as the existing key-pair service user
USE ROLE SECURITYADMIN;
GRANT ROLE TRANSFORMER TO USER AIRFLOW_SVC;
